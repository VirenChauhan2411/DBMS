

--Implement AFTER Triggers for Automatic Execution After Data Operations
--EMPLOYEE_LOG (LOGID, EID, OLDVALUE, NEWVALUE, FIELDNAME, OPERATIONTYPE, LOGDATE)
--From the table EMPLOYEE perform the following queries:


--Part – A:

--1. AFTER INSERT TRIGGER TO PRINT MESSAGE
CREATE TRIGGER TRG_EMP_INSERT
ON EMPLOYEE
AFTER INSERT
AS
BEGIN
    PRINT 'EMPLOYEE RECORD INSERTED SUCCESSFULLY';
END;

--2. AFTER UPDATE TRIGGER TO PRINT MESSAGE
CREATE TRIGGER TRG_EMP_UPDATE
ON EMPLOYEE
AFTER UPDATE
AS
BEGIN
    PRINT 'EMPLOYEE RECORD UPDATED SUCCESSFULLY';
END;

--3. AFTER DELETE TRIGGER TO PRINT MESSAGE
CREATE TRIGGER TRG_EMP_DELETE
ON EMPLOYEE
AFTER DELETE
AS
BEGIN
    PRINT 'EMPLOYEE RECORD DELETED SUCCESSFULLY';
END;

--4. AFTER UPDATE TRIGGER FOR SALARY INCREMENT
CREATE TRIGGER TRG_EMP_SALARY_INCREMENT
ON EMPLOYEE
AFTER UPDATE
AS
BEGIN
    IF UPDATE(SALARY)
        PRINT 'EMPLOYEE SALARY INCREMENTED SUCCESSFULLY';
END;

--5. AFTER INSERT TRIGGER TO CONVERT CITY INTO UPPERCASE
CREATE TRIGGER TRG_EMP_CITY_UPPERCASE
ON EMPLOYEE
AFTER INSERT
AS
BEGIN
    UPDATE EMPLOYEE
    SET CITY = UPPER(CITY)
    WHERE EID IN (SELECT EID FROM INSERTED);
END;


--Part – B:

--6. Create trigger for updating employee city and printing old city and new city name.
CREATE TRIGGER TRG_EMP_CITY_UPDATE
ON EMPLOYEE
AFTER UPDATE
AS
BEGIN
    IF UPDATE(CITY)
    BEGIN
        SELECT DELETED.CITY AS OLD_CITY, INSERTED.CITY AS NEW_CITY
        FROM DELETED INNER JOIN INSERTED ON DELETED.EID = INSERTED.EID;
        PRINT 'EMPLOYEE CITY UPDATED SUCCESSFULLY';
    END
END;


--7. Create trigger for automatically setting CITY as 'RAJKOT' if no city value is entered during employee insertion.
CREATE TRIGGER TRG_EMP_CITY_DEFAULT
ON EMPLOYEE
AFTER INSERT
AS
BEGIN
    UPDATE EMPLOYEE
    SET CITY = 'RAJKOT'
    WHERE EID IN (SELECT EID FROM INSERTED) AND CITY IS NULL;
END;

--8. Create trigger for automatically adding current year in JOININGYEAR if no value is entered.
CREATE TRIGGER TRG_EMP_JOININGYEAR_DEFAULT
ON EMPLOYEE
AFTER INSERT
AS
BEGIN
    UPDATE EMPLOYEE
    SET JOININGYEAR = YEAR(GETDATE())
    WHERE EID IN (SELECT EID FROM INSERTED) AND JOININGYEAR IS NULL;
END;

--9. Create trigger for printing employee full name after new employee insertion.
CREATE TRIGGER TRG_EMP_FULLNAME_PRINT
ON EMPLOYEE
AFTER INSERT
AS
BEGIN
    DECLARE @FULLNAME VARCHAR(100);
    SELECT @FULLNAME = FIRSTNAME + ' ' + LASTNAME FROM INSERTED;
    PRINT 'NEW EMPLOYEE INSERTED: ' + @FULLNAME;
END;

--10. Create trigger for automatically assigning department as ‘GENERAL’ if DEPARTMENT value is NULL.
CREATE TRIGGER TRG_EMP_DEPT_DEFAULT
ON EMPLOYEE
AFTER INSERT
AS
BEGIN
    UPDATE EMPLOYEE
    SET DEPARTMENT = 'GENERAL'
    WHERE EID IN (SELECT EID FROM INSERTED) AND DEPARTMENT IS NULL;
END;

