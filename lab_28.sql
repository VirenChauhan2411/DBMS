--12. AFTER INSERT TRIGGER TO STORE NEW EMPLOYEE DETAILS IN EMPLOYEE_INSERT_LOG
CREATE TRIGGER TRG_EMP_INSERT_LOG
ON EMPLOYEE
AFTER INSERT
AS
BEGIN
    INSERT INTO EMPLOYEE_INSERT_LOG(EID, FIRSTNAME, LASTNAME, DEPARTMENT, CITY, SALARY, INSERT_DATE)
    SELECT EID, FIRSTNAME, LASTNAME, DEPARTMENT, CITY, SALARY, GETDATE()
    FROM INSERTED;
END;

--13. AFTER UPDATE TRIGGER TO STORE OLD AND NEW FIRSTNAME IN NAME_CHANGE_LOG
CREATE TRIGGER TRG_EMP_NAME_CHANGE
ON EMPLOYEE
AFTER UPDATE
AS
BEGIN
    IF UPDATE(FIRSTNAME)
    BEGIN
        INSERT INTO NAME_CHANGE_LOG(EID, OLD_FIRSTNAME, NEW_FIRSTNAME, CHANGE_DATE)
        SELECT D.EID, D.FIRSTNAME, I.FIRSTNAME, GETDATE()
        FROM DELETED D INNER JOIN INSERTED I ON D.EID = I.EID;
    END
END;

--14. AFTER UPDATE TRIGGER TO STORE OLD AND NEW CITY IN CITY_UPDATE_LOG
CREATE TRIGGER TRG_EMP_CITY_CHANGE
ON EMPLOYEE
AFTER UPDATE
AS
BEGIN
    IF UPDATE(CITY)
    BEGIN
        INSERT INTO CITY_UPDATE_LOG(EID, OLD_CITY, NEW_CITY, CHANGE_DATE)
        SELECT D.EID, D.CITY, I.CITY, GETDATE()
        FROM DELETED D INNER JOIN INSERTED I ON D.EID = I.EID;
    END
END;

--15. INSTEAD OF INSERT TRIGGER TO REMOVE EXTRA SPACES FROM FIRSTNAME AND LASTNAME
CREATE TRIGGER TRG_EMP_REMOVE_SPACES
ON EMPLOYEE
INSTEAD OF INSERT
AS
BEGIN
    INSERT INTO EMPLOYEE(EID, FIRSTNAME, LASTNAME, DEPARTMENT, CITY, SALARY, JOININGYEAR)
    SELECT EID, LTRIM(RTRIM(FIRSTNAME)), LTRIM(RTRIM(LASTNAME)), DEPARTMENT, CITY, SALARY, JOININGYEAR
    FROM INSERTED;
END;


















































