--11. Create trigger for storing updated employee details such as EID, old salary, new salary, old department, new department, and update date into EMPLOYEE_UPDATE_LOG table.
CREATE OR ALTER TRIGGER TRG_SHOW_DETAILS
ON EMPLOYEE
AFTER UPDATE 
AS 
BEGIN
    IF UPDATE(SALARY)
    BEGIN
        INSERT INTO EMPLOYEE_UPDATE_LOG2
        (ID, OLDSALARY, NEWSALARY, OLDDEPARTMENT, NEWDEPARTMENT,  UPDATEDATE)

        SELECT I.EID , D.SALARY,I.SALARY,D.DEPARTMENT,I.DEPARTMENT,GETDATE()
        FROM INSERTED I
        INNER JOIN DELETED D 
        ON I.EID = D.EID
    END
END

